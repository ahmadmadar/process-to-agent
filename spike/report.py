"""Write the spike metrics and the sign-off queue view from the latest run per model.

Outputs:
  spike/metrics.md                  pass rate, escalation correctness, cost, latency per model
  spike/queues/<model>.md           sign-off queue view (US-12, G6): what each person would see

The recommendation in spike/results.md is the consultant's and is not written here.

Run: .venv/bin/python spike/report.py
"""
import json
from pathlib import Path

SPIKE = Path(__file__).resolve().parent
NOTE = "> Fictional engagement for portfolio purposes. The client, stakeholders and data are synthetic."
GROUP_LABEL = {"sample": "Sample (excl. info gap)", "info_gap": "Info gap (E-c)", "constructed": "Constructed (rule coverage)"}
LINE = 10_000  # v1 Parameters, assumption A2


def latest_runs():
    runs = {}
    for p in sorted((SPIKE / "runs").glob("*.json")):
        s = json.loads(p.read_text())
        runs[s["model"]] = s  # sorted by run_id timestamp, so the last one wins
    return runs


def traces_for(run):
    path = SPIKE / "traces" / f"{run['model']}.jsonl"
    return [t for t in map(json.loads, open(path)) if t["run_id"] == run["run_id"]]


def pct(n, d):
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "—"


def metrics_md(runs):
    out = ["# Spike Metrics", "", NOTE, "",
           "Generated by `spike/report.py` from the latest run per model. Groups are reported",
           "separately and never combined (EV3, E-c). Scoring conventions: `spike/expected-outcomes-v1.md`.", ""]
    models = sorted(runs)
    out += ["## Runs", "", "| Model | Run | Effort | Evaluations | Errors |", "|---|---|---|---|---|"]
    for m in models:
        r = runs[m]
        errs = sum(g["errors"] for g in r["metrics"]["groups"].values())
        out.append(f"| {m} | {r['run_id']} | {r['effort'] or 'model default'} | {r['metrics']['evaluations']} | {errs} |")
    out += ["", "## Pass rate and routing", "",
            "| Model | Group | Pass | Must-escalate routed to escalate | Escalated when not expected | Autonomous* → autonomous | Autonomous* → gate-held (R14) | Triggers match |",
            "|---|---|---|---|---|---|---|---|"]
    for m in models:
        for g, x in runs[m]["metrics"]["groups"].items():
            out.append(f"| {m} | {GROUP_LABEL[g]} | {pct(x['passed'], x['snapshots'])} | "
                       f"{pct(x['escalated_correctly'], x['must_escalate'])} | {x['escalated_when_not_expected']} | "
                       f"{pct(x['autonomous'], x['autonomous_star'])} | {pct(x['gate_held'], x['autonomous_star'])} | "
                       f"{pct(x['triggers_match'], x['snapshots'])} |")
    out += ["", "## Cost and latency", "",
            "| Model | Total cost | Cost per evaluation | Cost per claim (2 snapshots) | Latency p50 | Latency p95 | Input | Cache write | Cache read | Output |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for m in models:
        x = runs[m]["metrics"]
        t = x["tokens"]
        out.append(f"| {m} | ${x['cost_total_usd']:.4f} | ${x['cost_per_evaluation_usd']:.5f} | ${x['cost_per_claim_usd']:.5f} | "
                   f"{x['latency_p50_s']:.1f}s | {x['latency_p95_s']:.1f}s | {t['input_tokens']:,} | "
                   f"{t['cache_creation_input_tokens']:,} | {t['cache_read_input_tokens']:,} | {t['output_tokens']:,} |")
    out += ["", "## Failed snapshots", "", "| Model | Eval id | Fields wrong | Error |", "|---|---|---|---|"]
    for m in models:
        for eid, r in runs[m]["results"].items():
            if not r["pass"]:
                wrong = ", ".join(k for k, v in r["fields"].items() if not v) or "—"
                out.append(f"| {m} | {eid} | {wrong} | {r['error'] or ''} |")
    out += ["", "## Self-reported confidence (P1 calibration input)", "",
            "Every snapshot that reached step 4.", "",
            "| Model | Eval id | Rubric score | Self-reported confidence | Route | Rule | Pass |", "|---|---|---|---|---|---|---|"]
    for m in models:
        for t in traces_for(runs[m]):
            o = t["output"] or {}
            if o.get("self_reported_confidence") is not None:
                out.append(f"| {m} | {t['eval_id']} | {o.get('rubric_score')} | {o['self_reported_confidence']} | "
                           f"{o.get('route')} | {o.get('rule_applied')} | {'yes' if t['score']['pass'] else 'no'} |")
    return "\n".join(out) + "\n"


def cell(s):
    return str(s if s is not None else "—").replace("|", "\\|").replace("\n", " ")


def queue_md(run):
    """State after each case's decision-point evaluation. Key accounts first (G6)."""
    latest = {}
    for t in traces_for(run):
        if t["output"]:
            latest[t["claim_id"]] = t  # decision point follows intake in the eval set
    rows = sorted(latest.values(), key=lambda t: (not t["inputs"]["key_account"], t["claim_id"]))

    def section(title, pick, cols, fmt):
        sel = [t for t in rows if pick(t)]
        lines = [f"## {title} ({len(sel)})", ""]
        if not sel:
            return lines + ["None.", ""]
        lines += ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        lines += ["| " + " | ".join(cell(v) for v in fmt(t)) + " |" for t in sel]
        return lines + [""]

    o = lambda t: t["output"]
    amt = lambda t: f"{t['inputs']['amount_claimed']:,.2f}"
    key = lambda t: "Key" if t["inputs"]["key_account"] else ""
    signoff_cols = ["Claim", "Account", "Claimed", "Draft decision", "Proposed amount", "Rule", "Flags", "Rationale"]
    signoff = lambda t: [t["claim_id"], key(t), amt(t), o(t)["decision"], o(t)["amount"], o(t)["rule_applied"],
                         ", ".join(o(t)["triggers"]), o(t)["rationale"]]
    is_signoff = lambda t: o(t)["route"] == "sign_off"

    out = [f"# Sign-off Queue View: {run['model']}", "", NOTE, "",
           f"Generated by `spike/report.py` from run `{run['run_id']}`. Each claim is shown in the state",
           "its latest evaluation left it. Within each queue, key-account claims come first (G6).", ""]
    out += section("Sign-off: specialists (claimed amount ≤ $10,000)",
                   lambda t: is_signoff(t) and t["inputs"]["amount_claimed"] <= LINE, signoff_cols, signoff)
    out += section("Sign-off: claims lead (claimed amount > $10,000)",
                   lambda t: is_signoff(t) and t["inputs"]["amount_claimed"] > LINE, signoff_cols, signoff)
    out += section("Escalations (fact pack, no decision)", lambda t: o(t)["route"] == "escalate",
                   ["Claim", "Account", "Claimed", "Queue", "Triggers", "Reefer clock", "Insurer dates", "Expedite due", "Missing documents"],
                   lambda t: [t["claim_id"], key(t), amt(t), (o(t)["fact_pack"] or {}).get("queue"),
                              ", ".join(o(t)["triggers"]),
                              ((o(t)["fact_pack"] or {}).get("clocks") or {}).get("reefer"),
                              json.dumps(((o(t)["fact_pack"] or {}).get("clocks") or {}).get("insurer")),
                              ((o(t)["fact_pack"] or {}).get("expedite") or {}).get("answer_due"),
                              ", ".join(c["item"] for c in (o(t)["fact_pack"] or {}).get("checklist_status", [])
                                        if c["status"] == "missing")])
    out += section("Autonomous: reviewer list (US-11)", lambda t: o(t)["route"] == "autonomous",
                   ["Claim", "Account", "Claimed", "Decision", "Amount", "Rubric", "Confidence", "Rationale"],
                   lambda t: [t["claim_id"], key(t), amt(t), o(t)["decision"], o(t)["amount"], o(t)["rubric_score"],
                              o(t)["self_reported_confidence"], o(t)["rationale"]])
    out += section("Awaiting documents (hold)", lambda t: o(t)["status"] == "held",
                   ["Claim", "Account", "Claimed", "Missing", "Fallback date", "Duplicate flag"],
                   lambda t: [t["claim_id"], key(t), amt(t), ", ".join((o(t)["hold"] or {}).get("missing_items", [])),
                              (o(t)["hold"] or {}).get("fallback_date"), (o(t)["hold"] or {}).get("duplicate_flag")])
    return "\n".join(out)


def main():
    runs = latest_runs()
    if not runs:
        raise SystemExit("no runs in spike/runs/")
    (SPIKE / "metrics.md").write_text(metrics_md(runs))
    (SPIKE / "queues").mkdir(exist_ok=True)
    for m, r in runs.items():
        (SPIKE / "queues" / f"{m}.md").write_text(queue_md(r))
    print(f"wrote spike/metrics.md and {len(runs)} queue view(s)")


if __name__ == "__main__":
    main()
