"""Trigger table for the eval sample (data/released/eval_sample.csv).

Lists, per claim, the released fields that the decision tree's checks read,
and counts how many claims carry each trigger. It does not compute a route or
a decision: expected outcomes are the consultant's.

Thresholds are the design-doc values: $10k (provisional, C2/C5; D3) and the
deductible, assumed $25k until the CFO confirms it (D1; T2:L16). Both are
measured on the claimed amount (G4). FALLBACK_DEADLINE_DAYS = 14 (P2).

Run: python3 analysis/eval_sample_triggers.py > analysis/eval-sample-triggers.md
"""
import csv
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REL = ROOT / "data" / "released"

TEN_K = 10_000
DEDUCTIBLE_ASSUMED = 25_000
FALLBACK_DEADLINE_DAYS = 14


def days(a, b):
    if not a or not b:
        return None
    return (date.fromisoformat(b[:10]) - date.fromisoformat(a[:10])).days


def yn(flag):
    return "Y" if flag else ""


sample = list(csv.DictReader(open(REL / "eval_sample.csv")))
r2 = {r["claim_id"]: r for r in csv.DictReader(open(REL / "claims_r2_fields.csv"))}

rows = []
for c in sample:
    amt = float(c["amount_claimed"])
    d = days(c["received_at"], c["docs_completed_at"])
    extra = r2.get(c["claim_id"], {})
    rows.append({
        "id": c["claim_id"],
        "type": c["claim_type"],
        "claimed": amt,
        "gt10k": amt > TEN_K,
        "gt_ded": amt > DEDUCTIBLE_ASSUMED,
        "reefer": c["reefer_flag"] == "Y",
        "key": c["key_account"] == "Y",
        "clean_pod_shortage": c["claim_type"] == "shortage" and c["pod_exception"] == "N",
        "docs": "/".join(f"{k}:{c[k + '_received']}" for k in ("photos", "invoice", "bol")),
        "days_docs": d,
        "never_complete": not c["docs_completed_at"],
        "past_fallback": (d is not None and d > FALLBACK_DEADLINE_DAYS),
        "dup": extra.get("prior_payment_same_shipment") == "Y",
        "in_r2": bool(extra),
        "am": c["decided_by_role"] == "account_manager",
        "outcome": c["outcome"],
        "reason": c["denial_reason"],
    })

n = len(rows)
print("# Eval Sample: Trigger Table\n")
print("> Fictional engagement for portfolio purposes. The client, stakeholders and data are synthetic.\n")
print("Generated by `analysis/eval_sample_triggers.py` from `data/released/eval_sample.csv`")
print("(release 2) and `claims_r2_fields.csv`. It shows which decision-tree inputs each")
print("claim carries. **It does not compute a route or a decision**; expected outcomes are")
print("the consultant's. The historical outcome is shown for reference only: it is what")
print("happened under the current process, not the expected outcome under the redesign.\n")
print(f"Thresholds: $10k (provisional; D3); deductible assumed ${DEDUCTIBLE_ASSUMED:,} (D1); both on the claimed")
print(f"amount (G4). `FALLBACK_DEADLINE_DAYS` = {FALLBACK_DEADLINE_DAYS} (P2).\n")

print(f"## Trigger counts ({n} claims)\n")
print("| Check | Tree step / row | Claims |")
print("|---|---|---|")
counts = [
    ("Loss claim", "Step 0 / R16", sum(r["type"] == "loss" for r in rows)),
    ("Reefer equipment (`reefer_flag` = Y)", "Step 1 / R1", sum(r["reefer"] for r in rows)),
    ("Claimed amount above assumed deductible ($25k)", "Step 1 / R4", sum(r["gt_ded"] for r in rows)),
    ("Claimed amount above $10k, at or below $25k", "R13", sum(r["gt10k"] and not r["gt_ded"] for r in rows)),
    ("Documents never completed", "Step 2 / R5–R6", sum(r["never_complete"] for r in rows)),
    (f"Documents completed after more than {FALLBACK_DEADLINE_DAYS} days", "Step 2 / R6", sum(r["past_fallback"] for r in rows)),
    ("Prior payment on the same shipment", "Step 3 / R7", sum(r["dup"] for r in rows)),
    ("Key account", "G6 (priority, not routing)", sum(r["key"] for r in rows)),
    ("Shortage with clean POD (`pod_exception` = N)", "Step 7 / E6a", sum(r["clean_pod_shortage"] for r in rows)),
    ("Historically decided by an account manager", "Context for C4/E4 only", sum(r["am"] for r in rows)),
]
for label, step, k in counts:
    print(f"| {label} | {step} | {k} |")

missing = [r["id"] for r in rows if not r["in_r2"]]
if missing:
    print(f"\nNot found in `claims_r2_fields.csv` (duplicate check unavailable): {', '.join(missing)}")

print("\n## Not derivable from the released data\n")
print("These checks have no field in the eval sample. A claim can only test them if")
print("the consultant adds the input to the eval case (for example, a synthetic")
print("expedite request or temperature allegation in the claim text).\n")
print("| Check | Tree step / row | Why not derivable |")
print("|---|---|---|")
print("| Temperature-excursion allegation | Step 1 / R1 (G5) | No allegation field; only `reefer_flag` and `temp_log_obtained` |")
print("| Cold-chain contract customer | Step 1 / R2 | Customers are named in T2:L44, but the release has `customer_id` only, with no name mapping |")
print("| Account-manager expedite request | Step 1 / R3 | No request field; `decided_by_role` records who decided historically, not a request |")
print("| Invoice mismatch | Step 3 / R8 | `invoice_received` flag only; no invoice amount |")
print("| Outside the customer filing window | Step 3 / R9 | No window length in the data; the historical denial reason is an outcome, not an input |")
print("| Withdrawal | G12 | No withdrawn status in the sample |")
print("| Confidence gates | Step 6 / R14 (G11) | Produced by the agent at run time (P1 unset) |")

print("\n## Per-claim inputs\n")
print("Docs = photos / invoice / BOL received flags. Days = receipt to documents complete (blank = never completed).\n")
print("| Claim | Type | Claimed | >$10k | >$25k | Reefer | Key acct | Clean-POD shortage | Docs | Days | >14d | Prior pmt same shipment | Hist. decided by AM | Hist. outcome | Hist. reason |")
print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
for r in sorted(rows, key=lambda r: r["id"]):
    dd = "" if r["days_docs"] is None else r["days_docs"]
    print(f"| {r['id']} | {r['type']} | {r['claimed']:,.2f} | {yn(r['gt10k'])} | {yn(r['gt_ded'])} | {yn(r['reefer'])} | {yn(r['key'])} | "
          f"{yn(r['clean_pod_shortage'])} | {r['docs']} | {dd} | {yn(r['past_fallback'] or r['never_complete'])} | {yn(r['dup'])} | "
          f"{yn(r['am'])} | {r['outcome']} | {r['reason']} |")
